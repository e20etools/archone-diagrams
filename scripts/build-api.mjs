// Bundles the AI endpoint into self-contained files the hosts can run without a compile step:
//   api/ai.js                           Vercel Function behind /api/ai
//   api/apm.js                          Vercel Function behind /api/apm, which reads the APM feeds
//   supabase/functions/ai/handler.js    used by the Supabase / Lovable Cloud Edge Function
//   supabase/functions/api/handler.js   the public REST API, served by a Supabase Edge Function
//   supabase/functions/mcp/handler.js   the MCP server for assistants, served the same way
//   gate/archone-gate.mjs               the pull-request gate, run with Node in a repository's CI
// `--check` verifies that the committed files match the source, without writing anything.
import { mkdtemp, readFile, rm, mkdir, copyFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "vite";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const targets = [
  { entry: "server/vercel-entry.ts", out: "api/ai.js" },
  { entry: "server/apm-vercel-entry.ts", out: "api/apm.js" },
  { entry: "server/edge-entry.ts", out: "supabase/functions/ai/handler.js" },
  { entry: "server/api-entry.ts", out: "supabase/functions/api/handler.js" },
  { entry: "server/mcp-entry.ts", out: "supabase/functions/mcp/handler.js" },
  // The pull-request gate runs under Node in a repository's CI, not on a host of ours.
  { entry: "server/gate-entry.ts", out: "gate/archone-gate.mjs", node: true },
];
const check = process.argv.includes("--check");
const banner = "// Generated by `npm run build:api`. Do not edit: change the source under src/lib and rebuild.";

const tmp = await mkdtemp(join(tmpdir(), "archone-api-"));
let stale = false;
try {
  for (const [i, target] of targets.entries()) {
    const outDir = join(tmp, String(i));
    await build({
      root,
      configFile: false,
      logLevel: "error",
      publicDir: false,
      // Everything is inlined, so the function has no node_modules to resolve on the host.
      ssr: { noExternal: true, target: target.node ? "node" : "webworker" },
      build: {
        ssr: resolve(root, target.entry),
        outDir,
        emptyOutDir: true,
        minify: false,
        target: "es2022",
        rollupOptions: { output: { format: "es", entryFileNames: "out.js", banner } },
      },
    });
    const built = join(outDir, "out.js");
    const destination = resolve(root, target.out);
    if (check) {
      const [fresh, committed] = await Promise.all([readFile(built, "utf8"), readFile(destination, "utf8").catch(() => "")]);
      if (fresh !== committed) {
        stale = true;
        console.error(`${target.out} is out of date. Run: npm run build:api`);
      }
    } else {
      await mkdir(dirname(destination), { recursive: true });
      await copyFile(built, destination);
      console.log(`built ${target.out}`);
    }
  }
} finally {
  await rm(tmp, { recursive: true, force: true });
}
if (stale) process.exit(1);
if (check) console.log("AI endpoint bundles are up to date.");
