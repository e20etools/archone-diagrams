/**
 * The vendor-neutral part of the library: what an IT estate is made of, grouped the way
 * architects and CMDBs group it. Each entry is [name, icon, kind?, profile?, other names?].
 * The kind is one of the model's object types (it decides levels, views and checks); the
 * icon is a Lucide icon chosen to show what the thing does; the profile is the basic
 * information it asks for. A missing kind or profile takes the section's.
 */

